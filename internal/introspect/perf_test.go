// perfSchema builds 250 tables with 2,000 columns, 300 foreign keys and 500
// indexes in schema perf, and a table with 1,000 partitions in schema parts.
func perfSchema() string {
	var b strings.Builder
	b.WriteString("CREATE SCHEMA perf; CREATE SCHEMA parts;\n")
	fks := 0
	for i := range 250 {
		cols := []string{"id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"}
		if i > 0 {
			cols = append(cols, fmt.Sprintf("parent_id bigint REFERENCES perf.t%03d (id) ON DELETE CASCADE", i-1))
			fks++
		}
		if i > 0 && i <= 51 {
			cols = append(cols, fmt.Sprintf("other_id bigint REFERENCES perf.t%03d (id)", i/2))
			fks++
		}
		for c := 0; len(cols) < 8; c++ {
			switch c % 4 {
			case 0:
				cols = append(cols, fmt.Sprintf("name_%d text NOT NULL DEFAULT ''", c))
			case 1:
				cols = append(cols, fmt.Sprintf("amount_%d numeric(12,2) CHECK (amount_%d >= 0)", c, c))
			case 2:
				cols = append(cols, fmt.Sprintf("created_%d timestamptz NOT NULL DEFAULT now()", c))
			default:
				cols = append(cols, fmt.Sprintf("flags_%d jsonb", c))
			}
		}
		fmt.Fprintf(&b, "CREATE TABLE perf.t%03d (%s);\n", i, strings.Join(cols, ", "))
		fmt.Fprintf(&b, "CREATE INDEX ON perf.t%03d (name_0, created_2) WHERE name_0 <> '';\n", i)
		fmt.Fprintf(&b, "COMMENT ON TABLE perf.t%03d IS 'table %d';\n", i, i)
	}
	if fks != 300 {
		panic(fks)
	}
	b.WriteString(`CREATE TABLE parts.events (id bigint NOT NULL, at int NOT NULL, ref bigint REFERENCES perf.t000 (id),
		payload text, PRIMARY KEY (id, at)) PARTITION BY RANGE (at);
CREATE INDEX ON parts.events (ref);
DO $$ BEGIN
  FOR i IN 0..999 LOOP
    EXECUTE format('CREATE TABLE parts.events_%s PARTITION OF parts.events FOR VALUES FROM (%s) TO (%s)', i, i * 10, i * 10 + 10);
  END LOOP;
END $$;
`)
	return b.String()
}

func TestIntrospectPerformance(t *testing.T) {
	for _, srv := range pgtest.Servers(t, "14", "18") {
		t.Run(srv.String(), func(t *testing.T) {
			d := srv.NewDB(t)
			d.Exec(t, perfSchema())

			measure := func(schemas []string) (time.Duration, *schema.Model) {
				var m *schema.Model
				var runs []time.Duration
				for i := range 6 {
					start := time.Now()
					var err error
					if m, err = Introspect(t.Context(), d.Admin, schemas, 30*time.Second); err != nil {
						t.Fatal(err)
					}
					if i > 0 { // the first run warms the server's caches
						runs = append(runs, time.Since(start))
					}
				}
				slices.Sort(runs)
				t.Logf("%s Introspect(%v): median %v of %v", srv, schemas, runs[2].Round(100*time.Microsecond), runs)
				return runs[2], m
			}

			med, m := measure([]string{"perf"})
			cols, fks, idx := 0, 0, 0
			for _, r := range m.Relations {
				cols += len(r.Columns)
				fks += len(r.ForeignKeys)
				idx += len(r.Indexes)
			}
			if len(m.Relations) != 250 || cols != 2000 || fks != 300 || idx != 500 {
				t.Fatalf("perf model: %d relations, %d columns, %d FKs, %d indexes", len(m.Relations), cols, fks, idx)
			}
			if med > 500*time.Millisecond {
				t.Errorf("250-table schema took %v, want < 500ms", med)
			}

			med, m = measure([]string{"perf", "parts"})
			ev := m.Relation(q("parts", "events"))
			if len(m.Relations) != 251 || ev == nil || len(ev.Partitions) != 1000 || len(ev.Indexes) != 2 || len(ev.ForeignKeys) != 1 {
				t.Fatalf("partitioned model: %d relations, events %+v", len(m.Relations), ev != nil)
			}
			if med > 2*time.Second {
				t.Errorf("schema with 1,000 partitions took %v, want < 2s", med)
			}
		})
	}
}
