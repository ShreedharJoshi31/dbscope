CREATE TABLE shop.customers (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email            text NOT NULL,
    first_name       text,
    last_name        text,
    phone            text,
    marketing_opt_in boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX customers_email_key ON shop.customers (lower(email));
COMMENT ON TABLE shop.customers IS 'Shoppers; separate from app.users';

CREATE TABLE shop.addresses (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES shop.customers (id) ON DELETE CASCADE,
    line1       text NOT NULL,
    line2       text,
    city        text NOT NULL,
    region      text,
    postal_code text NOT NULL,
    country     char(2) NOT NULL
);
CREATE INDEX addresses_customer_idx ON shop.addresses (customer_id);

CREATE TABLE shop.categories (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id integer REFERENCES shop.categories (id),
    name      text NOT NULL,
    slug      text NOT NULL UNIQUE
);

CREATE TABLE shop.products (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    category_id integer REFERENCES shop.categories (id) ON DELETE SET NULL,
    name        text NOT NULL,
    description text,
    status      shop.product_status NOT NULL DEFAULT 'draft',
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_search_idx ON shop.products USING gin (to_tsvector('english', name || ' ' || coalesce(description, '')));
COMMENT ON TABLE shop.products IS 'Catalogue entries; prices and stock live on variants';

CREATE TABLE shop.variants (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id    bigint NOT NULL REFERENCES shop.products (id) ON DELETE CASCADE,
    sku           varchar(32) NOT NULL UNIQUE,
    option_values jsonb NOT NULL DEFAULT '{}',
    price_cents   integer NOT NULL CHECK (price_cents >= 0),
    weight_grams  integer
);
CREATE INDEX variants_product_idx ON shop.variants (product_id);

CREATE TABLE shop.warehouses (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    varchar(8) NOT NULL UNIQUE,
    name    text NOT NULL,
    country char(2) NOT NULL
);

CREATE TABLE shop.inventory (
    warehouse_id smallint NOT NULL REFERENCES shop.warehouses (id),
    variant_id   bigint NOT NULL REFERENCES shop.variants (id) ON DELETE CASCADE,
    on_hand      integer NOT NULL DEFAULT 0,
    reserved     integer NOT NULL DEFAULT 0,
    available    integer GENERATED ALWAYS AS (on_hand - reserved) STORED,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (warehouse_id, variant_id),
    CHECK (reserved <= on_hand)
);
CREATE INDEX inventory_variant_idx ON shop.inventory (variant_id);
COMMENT ON TABLE shop.inventory IS 'Stock per variant per warehouse';

CREATE TABLE shop.carts (
    id          uuid PRIMARY KEY,
    customer_id bigint REFERENCES shop.customers (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shop.cart_items (
    cart_id    uuid NOT NULL REFERENCES shop.carts (id) ON DELETE CASCADE,
    variant_id bigint NOT NULL REFERENCES shop.variants (id),
    quantity   integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (cart_id, variant_id)
);

CREATE TABLE shop.orders (
    id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id         bigint NOT NULL REFERENCES shop.customers (id),
    shipping_address_id bigint REFERENCES shop.addresses (id),
    billing_address_id  bigint REFERENCES shop.addresses (id),
    status              shop.order_status NOT NULL DEFAULT 'pending',
    currency            char(3) NOT NULL DEFAULT 'USD',
    total_cents         bigint NOT NULL CHECK (total_cents >= 0),
    placed_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON shop.orders (customer_id, placed_at DESC) INCLUDE (status, total_cents);
CREATE INDEX orders_open_idx ON shop.orders (placed_at) WHERE status IN ('pending', 'paid');
COMMENT ON TABLE shop.orders IS 'Customer orders; totals are in the order currency';

CREATE TABLE shop.order_items (
    order_id         bigint NOT NULL REFERENCES shop.orders (id) ON DELETE CASCADE,
    line_no          smallint NOT NULL,
    variant_id       bigint NOT NULL REFERENCES shop.variants (id),
    quantity         integer NOT NULL CHECK (quantity > 0),
    unit_price_cents integer NOT NULL,
    PRIMARY KEY (order_id, line_no)
);
CREATE INDEX order_items_variant_idx ON shop.order_items (variant_id);

CREATE TABLE shop.payments (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id     bigint NOT NULL REFERENCES shop.orders (id),
    provider     text NOT NULL,
    provider_ref text NOT NULL,
    amount_cents bigint NOT NULL,
    status       text NOT NULL CHECK (status IN ('authorized', 'captured', 'failed', 'voided')),
    captured_at  timestamptz,
    UNIQUE (provider, provider_ref)
);
CREATE INDEX payments_order_idx ON shop.payments (order_id);

CREATE TABLE shop.refunds (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_id   bigint NOT NULL, -- no FK: imported nightly from the payment provider
    amount_cents bigint NOT NULL CHECK (amount_cents > 0),
    reason       text,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refunds_payment_idx ON shop.refunds (payment_id);

CREATE TABLE shop.shipments (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id        bigint NOT NULL REFERENCES shop.orders (id),
    warehouse_id    smallint NOT NULL REFERENCES shop.warehouses (id),
    carrier         text NOT NULL,
    tracking_number text,
    shipped_at      timestamptz,
    delivered_at    timestamptz
);
CREATE INDEX shipments_order_idx ON shop.shipments (order_id);

-- Composite foreign key onto order_items' composite primary key.
CREATE TABLE shop.shipment_items (
    shipment_id bigint NOT NULL REFERENCES shop.shipments (id) ON DELETE CASCADE,
    order_id    bigint NOT NULL,
    line_no     smallint NOT NULL,
    quantity    integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (shipment_id, order_id, line_no),
    FOREIGN KEY (order_id, line_no) REFERENCES shop.order_items (order_id, line_no)
);

CREATE TABLE shop.reviews (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id  bigint NOT NULL REFERENCES shop.products (id) ON DELETE CASCADE,
    customer_id bigint NOT NULL REFERENCES shop.customers (id),
    rating      smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body        text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (product_id, customer_id)
);

