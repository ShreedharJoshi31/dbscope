-- dbscope sample schema: a SaaS product (schema app) that bills its teams
-- (schema billing) and runs a web shop (schema shop).
--
-- internal/sample/model.json is generated from this file:
--   go test ./internal/sample -run TestModelJSON -update
--
-- A few columns deliberately have no declared foreign key so that FK
-- inference has something to find: app.events.user_id, app.audit_log.user_id,
-- billing.invoice_lines.subscription_id and shop.refunds.payment_id.
-- app.comments(commentable_type, commentable_id) is a polymorphic pair that
-- inference must leave alone.

CREATE SCHEMA app;
CREATE SCHEMA billing;
CREATE SCHEMA shop;

COMMENT ON SCHEMA app IS 'SaaS product: users, teams, access control, integrations';
COMMENT ON SCHEMA billing IS 'Subscriptions and invoicing for teams';
COMMENT ON SCHEMA shop IS 'Web shop: catalogue, orders, fulfilment';

CREATE TYPE app.user_status AS ENUM ('invited', 'active', 'suspended', 'deleted');
CREATE TYPE billing.subscription_status AS ENUM ('trialing', 'active', 'past_due', 'canceled', 'unpaid');
CREATE TYPE billing.billing_interval AS ENUM ('month', 'year');
CREATE TYPE shop.order_status AS ENUM ('pending', 'paid', 'fulfilled', 'cancelled', 'refunded');
CREATE TYPE shop.product_status AS ENUM ('draft', 'active', 'archived');

------------------------------------------------------------------------------
-- app
------------------------------------------------------------------------------

CREATE TABLE app.users (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email         text NOT NULL,
    display_name  text NOT NULL,
    status        app.user_status NOT NULL DEFAULT 'invited',
    password_hash text,
    mfa_enabled   boolean NOT NULL DEFAULT false,
    last_login_at timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON app.users (lower(email));
COMMENT ON TABLE app.users IS 'People who can sign in. One user can belong to many teams.';
COMMENT ON COLUMN app.users.email IS 'Unique case-insensitively';

CREATE TABLE app.teams (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    slug       text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]+$'),
    owner_id   bigint NOT NULL REFERENCES app.users (id),
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE app.teams IS 'Workspaces; the unit that subscribes and is billed';

CREATE TABLE app.roles (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     bigint REFERENCES app.teams (id) ON DELETE CASCADE,
    name        text NOT NULL,
    description text,
    UNIQUE NULLS NOT DISTINCT (team_id, name)
);
COMMENT ON COLUMN app.roles.team_id IS 'NULL for built-in roles shared by every team';

CREATE TABLE app.permissions (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    description text NOT NULL
);

CREATE TABLE app.role_permissions (
    role_id       integer NOT NULL REFERENCES app.roles (id) ON DELETE CASCADE,
    permission_id integer NOT NULL REFERENCES app.permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE app.memberships (
    team_id    bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    user_id    bigint NOT NULL REFERENCES app.users (id) ON DELETE CASCADE,
    role_id    integer NOT NULL REFERENCES app.roles (id),
    joined_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, user_id)
);
CREATE INDEX memberships_user_id_idx ON app.memberships (user_id);
COMMENT ON TABLE app.memberships IS 'Which users belong to which teams, and with what role';

CREATE TABLE app.invitations (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_id     bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    email       text NOT NULL,
    role_id     integer NOT NULL REFERENCES app.roles (id),
    invited_by  bigint NOT NULL REFERENCES app.users (id),
    token       text NOT NULL UNIQUE,
    expires_at  timestamptz NOT NULL,
    accepted_at timestamptz
);
CREATE INDEX invitations_pending_idx ON app.invitations (team_id, email) WHERE accepted_at IS NULL;

CREATE TABLE app.sessions (
    id         uuid PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES app.users (id) ON DELETE CASCADE,
    ip         inet,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_user_id_idx ON app.sessions (user_id);

CREATE TABLE app.api_keys (
    id           uuid PRIMARY KEY,
    team_id      bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    created_by   bigint REFERENCES app.users (id) ON DELETE SET NULL,
    name         text NOT NULL,
    prefix       varchar(12) NOT NULL UNIQUE,
    secret_hash  bytea NOT NULL,
    scopes       text[] NOT NULL DEFAULT '{}',
    last_used_at timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    revoked_at   timestamptz
);
CREATE INDEX api_keys_active_idx ON app.api_keys (team_id) INCLUDE (prefix) WHERE revoked_at IS NULL;
COMMENT ON TABLE app.api_keys IS 'Programmatic access tokens; only a hash of the secret is stored';

CREATE TABLE app.feature_flags (
    key             text PRIMARY KEY,
    description     text NOT NULL DEFAULT '',
    enabled         boolean NOT NULL DEFAULT false,
    rollout_percent smallint NOT NULL DEFAULT 0 CHECK (rollout_percent BETWEEN 0 AND 100),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.feature_flag_overrides (
    flag_key text NOT NULL REFERENCES app.feature_flags (key) ON UPDATE CASCADE ON DELETE CASCADE,
    team_id  bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    enabled  boolean NOT NULL,
    PRIMARY KEY (flag_key, team_id)
);

CREATE TABLE app.events (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_id     bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    user_id     bigint, -- no FK: events are kept after a user is deleted
    name        text NOT NULL,
    properties  jsonb NOT NULL DEFAULT '{}',
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX events_team_time_idx ON app.events (team_id, occurred_at DESC);
CREATE INDEX events_properties_idx ON app.events USING gin (properties jsonb_path_ops);
COMMENT ON TABLE app.events IS 'Product analytics events';

CREATE TABLE app.webhooks (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_id    bigint NOT NULL REFERENCES app.teams (id) ON DELETE CASCADE,
    url        text NOT NULL CHECK (url LIKE 'https://%'),
    secret     text NOT NULL,
    events     text[] NOT NULL,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.webhook_deliveries (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    webhook_id   bigint NOT NULL REFERENCES app.webhooks (id) ON DELETE CASCADE,
    event_id     bigint NOT NULL REFERENCES app.events (id) ON DELETE CASCADE,
    attempt      smallint NOT NULL DEFAULT 1,
    status_code  smallint,
    duration_ms  integer,
    attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX webhook_deliveries_webhook_idx ON app.webhook_deliveries (webhook_id, attempted_at DESC);

CREATE TABLE app.comments (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    author_id        bigint NOT NULL REFERENCES app.users (id),
    commentable_type text NOT NULL,
    commentable_id   bigint NOT NULL,
    body             text NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX comments_target_idx ON app.comments (commentable_type, commentable_id);
COMMENT ON TABLE app.comments IS 'Comments on any object, Rails polymorphic style';

CREATE TABLE app.audit_log (
    id         bigint GENERATED ALWAYS AS IDENTITY,
    at         timestamptz NOT NULL DEFAULT now(),
    team_id    bigint NOT NULL REFERENCES app.teams (id),
    user_id    bigint, -- no FK, so audit history outlives the user row
    action     text NOT NULL,
    target     text NOT NULL,
    details    jsonb,
    ip         inet,
    PRIMARY KEY (id, at)
) PARTITION BY RANGE (at);
CREATE INDEX audit_log_user_idx ON app.audit_log (user_id, at);
CREATE TABLE app.audit_log_2026_08 PARTITION OF app.audit_log FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');
CREATE TABLE app.audit_log_2026_09 PARTITION OF app.audit_log FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');
CREATE TABLE app.audit_log_2026_10 PARTITION OF app.audit_log FOR VALUES FROM ('2026-10-01') TO ('2026-11-01');
COMMENT ON TABLE app.audit_log IS 'Security-relevant actions, partitioned by month';

