CREATE VIEW shop.order_summaries AS
SELECT o.id, o.placed_at, o.status, o.total_cents, c.email AS customer_email,
       (SELECT count(*) FROM shop.order_items i WHERE i.order_id = o.id) AS item_count
FROM shop.orders o
JOIN shop.customers c ON c.id = o.customer_id;
COMMENT ON VIEW shop.order_summaries IS 'One row per order for support dashboards';

CREATE MATERIALIZED VIEW billing.mrr_by_plan AS
SELECT p.code AS plan_code, count(*) AS subscriptions,
       sum(CASE p.interval WHEN 'year' THEN p.price_cents / 12 ELSE p.price_cents END * s.seats) AS mrr_cents
FROM billing.subscriptions s
JOIN billing.plans p ON p.id = s.plan_id
WHERE s.status IN ('active', 'past_due')
GROUP BY p.code;
COMMENT ON MATERIALIZED VIEW billing.mrr_by_plan IS 'Monthly recurring revenue per plan, refreshed nightly';

