CREATE TABLE billing.plans (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           text NOT NULL UNIQUE,
    name           text NOT NULL,
    interval       billing.billing_interval NOT NULL,
    price_cents    integer NOT NULL CHECK (price_cents >= 0),
    currency       char(3) NOT NULL DEFAULT 'USD',
    seats_included integer NOT NULL DEFAULT 1,
    active         boolean NOT NULL DEFAULT true
);

CREATE TABLE billing.accounts (
    id                 bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_id            bigint NOT NULL UNIQUE REFERENCES app.teams (id),
    billing_email      text NOT NULL,
    company_name       text,
    tax_number         text,
    country            char(2) NOT NULL,
    balance_cents      bigint NOT NULL DEFAULT 0,
    created_at         timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE billing.accounts IS 'One billing account per team';

CREATE TABLE billing.payment_methods (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES billing.accounts (id) ON DELETE CASCADE,
    brand      text NOT NULL,
    last4      char(4) NOT NULL,
    exp_month  smallint NOT NULL CHECK (exp_month BETWEEN 1 AND 12),
    exp_year   smallint NOT NULL,
    is_default boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX payment_methods_one_default ON billing.payment_methods (account_id) WHERE is_default;

CREATE TABLE billing.subscriptions (
    id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id           bigint NOT NULL REFERENCES billing.accounts (id),
    plan_id              integer NOT NULL REFERENCES billing.plans (id),
    status               billing.subscription_status NOT NULL DEFAULT 'trialing',
    seats                integer NOT NULL DEFAULT 1 CHECK (seats > 0),
    current_period_start timestamptz NOT NULL,
    current_period_end   timestamptz NOT NULL,
    cancel_at            timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CHECK (current_period_end > current_period_start)
);
CREATE INDEX subscriptions_account_idx ON billing.subscriptions (account_id);
COMMENT ON TABLE billing.subscriptions IS 'A team''s plan over time; one active row per account';

CREATE TABLE billing.coupons (
    code        text PRIMARY KEY,
    percent_off numeric(5,2) NOT NULL CHECK (percent_off > 0 AND percent_off <= 100),
    max_redemptions integer,
    expires_at  timestamptz
);

CREATE TABLE billing.discounts (
    subscription_id bigint NOT NULL REFERENCES billing.subscriptions (id) ON DELETE CASCADE,
    coupon_code     text NOT NULL REFERENCES billing.coupons (code),
    applied_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (subscription_id, coupon_code)
);

CREATE TABLE billing.invoices (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id      bigint NOT NULL REFERENCES billing.accounts (id),
    subscription_id bigint REFERENCES billing.subscriptions (id),
    number          text NOT NULL UNIQUE,
    status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'open', 'paid', 'void', 'uncollectible')),
    currency        char(3) NOT NULL,
    subtotal_cents  bigint NOT NULL DEFAULT 0,
    tax_cents       bigint NOT NULL DEFAULT 0,
    total_cents     bigint GENERATED ALWAYS AS (subtotal_cents + tax_cents) STORED,
    issued_at       timestamptz,
    due_at          timestamptz,
    paid_at         timestamptz
);
CREATE INDEX invoices_account_idx ON billing.invoices (account_id, issued_at DESC);
COMMENT ON TABLE billing.invoices IS 'Invoices issued to billing accounts';

CREATE TABLE billing.invoice_lines (
    invoice_id        bigint NOT NULL REFERENCES billing.invoices (id) ON DELETE CASCADE,
    line_no           smallint NOT NULL,
    description       text NOT NULL,
    subscription_id   bigint, -- no FK: lines are copied from usage at invoice time
    quantity          integer NOT NULL DEFAULT 1,
    unit_amount_cents bigint NOT NULL,
    amount_cents      bigint GENERATED ALWAYS AS (quantity * unit_amount_cents) STORED,
    PRIMARY KEY (invoice_id, line_no)
);

CREATE TABLE billing.credit_notes (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    invoice_id   bigint NOT NULL REFERENCES billing.invoices (id),
    amount_cents bigint NOT NULL CHECK (amount_cents > 0),
    reason       text,
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE billing.usage_records (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subscription_id bigint NOT NULL REFERENCES billing.subscriptions (id) ON DELETE CASCADE,
    metric          text NOT NULL,
    quantity        bigint NOT NULL,
    recorded_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX usage_records_sub_metric_idx ON billing.usage_records (subscription_id, metric, recorded_at);

