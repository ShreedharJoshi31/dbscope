func TestCheck(t *testing.T) {
	for text, want := range map[string]guard.Reason{
		"SELECT * FROM shop.customers":                              "",
		"with x as (select 1 a from dual) select a from x;":         "",
		`SELECT "update", 'delete' FROM t -- drop`:                  "",
		"SELECT q'[it's ]' FROM dual":                               "",
		"SELECT dbms_random.value FROM dual":                        "",
		"SELECT 1 FROM dual; SELECT 2 FROM dual":                    guard.MultipleStatements,
		"DELETE FROM t":                                             guard.NotSelect,
		"BEGIN NULL; END;":                                          guard.MultipleStatements,
		"SELECT * FROM t FOR UPDATE":                                guard.LockingClause,
		"SELECT utl_http.request('http://x') FROM dual":             guard.FunctionNotAllowed,
		"SELECT sys.dbms_pipe.receive_message('p') FROM dual":       guard.FunctionNotAllowed,
		"SELECT dbms_xmlgen.getxml('select 1 from dual') FROM dual": guard.FunctionNotAllowed,
		"SELECT q'{ ' }' || x INTO y FROM dual":                     guard.SelectInto,
		"   ":                                                       guard.Syntax,
	} {
		err := Check(text)
		var ge *guard.Error
		switch {
		case want == "" && err != nil:
			t.Errorf("Check(%q) = %v", text, err)
		case want != "" && (!errors.As(err, &ge) || ge.Reason != want):
			t.Errorf("Check(%q) = %v, want %s", text, err, want)
		}
	}
}

