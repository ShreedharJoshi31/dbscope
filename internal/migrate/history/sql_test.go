// exec runs each ;-separated statement on its own (MySQL is opened without multi-statements).
func execAll(t *testing.T, run func(string) error, stmts ...string) {
	t.Helper()
	for _, s := range stmts {
		for _, one := range strings.Split(s, ";") {
			if strings.TrimSpace(one) == "" {
				continue
			}
			if err := run(one); err != nil {
				t.Fatalf("%s: %v", one, err)
			}
		}
	}
}

func check(t *testing.T, c sqlCase, r Result) {
	t.Helper()
	if c.warning != "" && !slices.ContainsFunc(r.Warnings, func(w string) bool { return strings.Contains(w, c.warning) }) {
		t.Errorf("warnings %q lack %q", r.Warnings, c.warning)
	}
	if c.tool == "" {
		if r.Pending != nil {
			t.Fatalf("pending %+v", r.Pending)
		}
		return
	}
	if r.Pending == nil {
		t.Fatalf("no pending; warnings %q", r.Warnings)
	}
	changed := c.changed
	if changed == nil {
		changed = []string{}
	}
	if r.Pending.Tool != c.tool || !slices.Equal(r.Pending.Applied, c.applied) || !slices.Equal(r.Pending.Changed, changed) {
		t.Fatalf("got %+v, want tool %s applied %v changed %v", r.Pending, c.tool, c.applied, changed)
	}
}

// TestGolangMigrateCLI runs the real golang-migrate CLI, when it is installed,
// so the history read is checked against the table the tool itself writes.
func TestGolangMigrateCLI(t *testing.T) {
	bin, err := exec.LookPath("migrate")
	if err != nil {
		t.Skip("the golang-migrate CLI (migrate) is not on PATH")
	}
	srv := pgtest.Servers(t, "17")[0]
	d := srv.NewDB(t)
	p, password := d.Superuser(t)
	dsn := (&url.URL{Scheme: "postgres", User: url.UserPassword(p.User, password), Host: net.JoinHostPort(p.Host, strconv.Itoa(p.Port)),
		Path: "/" + p.Database, RawQuery: "sslmode=disable"}).String()
	dir := t.TempDir()
	write := func(name, sql string) ingest.Input {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(sql), 0o600); err != nil {
			t.Fatal(err)
		}
		return ingest.Input{Name: "migrations/" + name, SQL: sql}
	}
	files := []ingest.Input{
		write("1_a.up.sql", "CREATE TABLE a (id int);"), write("1_a.down.sql", "DROP TABLE a;"),
		write("2_b.up.sql", "CREATE TABLE b (id int);"), write("2_b.down.sql", "DROP TABLE b;"),
		write("3_c.up.sql", "CREATE TABLE c (id int); SELECT 1/0;"),
	}
	run := func(args ...string) {
		out, _ := exec.Command(bin, append([]string{"-path", dir, "-database", dsn}, args...)...).CombinedOutput()
		t.Logf("migrate %s: %s", args, strings.ReplaceAll(string(out), password, "***"))
	}
	run("up", "2")
	check(t, sqlCase{tool: "golang-migrate", applied: []string{"migrations/1_a.up.sql", "migrations/2_b.up.sql"}}, SQL(t.Context(), Pgx(d.Admin), Postgres, files))
	run("up") // 3 fails on division by zero and leaves version 3 dirty
	check(t, sqlCase{tool: "golang-migrate", applied: []string{"migrations/1_a.up.sql", "migrations/2_b.up.sql"}, warning: "version 3 dirty"},
		SQL(t.Context(), Pgx(d.Admin), Postgres, files))
}

func setupSQL(c sqlCase, d Dialect) []string {
	var out []string
	for _, tool := range c.tools {
		out = append(out, ddl[tool][d])
	}
	return append(out, c.rows...)
}

func TestPostgres(t *testing.T) {
	srv := pgtest.Servers(t, "17")[0]
	for _, c := range sqlCases() {
		t.Run(c.name, func(t *testing.T) {
			d := srv.NewDB(t)
			for _, s := range setupSQL(c, Postgres) {
				d.Exec(t, s)
			}
			check(t, c, SQL(t.Context(), Pgx(d.Admin), Postgres, c.files))
		})
	}
}

func TestSQLite(t *testing.T) {
	for _, c := range sqlCases() {
		t.Run(c.name, func(t *testing.T) {
			db, err := sql.Open("sqlite", filepath.Join(t.TempDir(), "h.db"))
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			execAll(t, func(s string) error { _, err := db.Exec(s); return err }, setupSQL(c, SQLite)...)
			check(t, c, SQL(t.Context(), DB(db), SQLite, c.files))
		})
	}
}

func TestMySQL(t *testing.T) {
	p := mytest.Server(t, "mysql")
	root, err := mysql.Open(p, mytest.Password, 30*time.Second)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	for i, c := range sqlCases() {
		t.Run(c.name, func(t *testing.T) {
			name := fmt.Sprintf("h%d", i)
			if _, err := root.Exec("CREATE DATABASE " + name); err != nil {
				t.Fatal(err)
			}
			q := p
			q.Database = name
			db, err := mysql.Open(q, mytest.Password, 30*time.Second)
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			execAll(t, func(s string) error { _, err := db.Exec(s); return err }, setupSQL(c, MySQL)...)
			check(t, c, SQL(t.Context(), DB(db), MySQL, c.files))
		})
	}
}

func TestClickHouse(t *testing.T) {
	p := mytest.ClickHouse(t, "26.8")
	admin, err := clickhouse.Connect(p, mytest.ClickHousePassword)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	ctx := context.Background()
	for i, c := range sqlCases() {
		if c.chRows == nil && c.tool != "" {
			continue // Flyway, dbmate and Prisma histories are not read on ClickHouse
		}
		if len(c.tools) > 0 && ddl[c.tools[0]][ClickHouse] == "" {
			continue
		}
		t.Run(c.name, func(t *testing.T) {
			name := fmt.Sprintf("h%d", i)
			if err := admin.Conn.Exec(ctx, "CREATE DATABASE "+name); err != nil {
				t.Fatal(err)
			}
			q := p
			q.Database = name
			cc, err := clickhouse.Connect(q, mytest.ClickHousePassword)
			if err != nil {
				t.Fatal(err)
			}
			defer cc.Close()
			var stmts []string
			for _, tool := range c.tools {
				stmts = append(stmts, ddl[tool][ClickHouse])
			}
			for _, s := range append(stmts, c.chRows...) {
				if err := cc.Conn.Exec(ctx, s); err != nil {
					t.Fatalf("%s: %v", s, err)
				}
			}
			r := SQL(t.Context(), ClickHouseConn(cc.Conn), ClickHouse, c.files)
			if c.name == "no history" {
				c.warning = "looked for schema_migrations and goose_db_version"
			}
			check(t, c, r)
		})
	}
	t.Run("dbmate's ClickHouse table", func(t *testing.T) {
		// dbmate pkg/driver/clickhouse: no dirty column, so not golang-migrate's.
		if err := admin.Conn.Exec(ctx, "CREATE DATABASE hdbmate"); err != nil {
			t.Fatal(err)
		}
		q := p
		q.Database = "hdbmate"
		cc, err := clickhouse.Connect(q, mytest.ClickHousePassword)
		if err != nil {
			t.Fatal(err)
		}
		defer cc.Close()
		if err := cc.Conn.Exec(ctx, `create table if not exists schema_migrations (version String, ts DateTime default now(), applied UInt8 default 1) engine = ReplacingMergeTree(ts) primary key version order by version`); err != nil {
			t.Fatal(err)
		}
		check(t, sqlCase{warning: "not golang-migrate's"}, SQL(t.Context(), ClickHouseConn(cc.Conn), ClickHouse, []ingest.Input{{Name: "20240101120000_a.sql"}}))
	})
}
