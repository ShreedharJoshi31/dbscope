import { baseWords } from "@/entities/migration-finding/model/describe";
import { RATINGS, ratingMeta } from "@/entities/migration-finding/model/rating";
import type { ReviewModel } from "@/entities/migration-finding/model/review-model";
import { DEFAULT_RISK_SORT, riskRows, sortRiskRows } from "@/entities/migration-finding/model/risk-rows";

/**
 * Report text comes from migration files (names, SQL fragments in messages),
 * so it is escaped: it must not turn into links, HTML, headings or extra
 * table cells when pasted into a PR comment.
 */
export function escapeMarkdown(value: string): string {
  return value
    .replace(/\r?\n/g, " ")
    .replace(/[\\`*_[\]<>|~]/g, (c) => `\\${c}`)
    .trim();
}

/** A code span that survives backticks and pipes in the value (GFM tables need `\|` even inside code). */
export function codeSpan(value: string): string {
  const flat = value.replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
  const longest = Math.max(0, ...(flat.match(/`+/g) ?? []).map((run) => run.length));
  const fence = "`".repeat(longest + 1);
  const pad = flat.startsWith("`") || flat.endsWith("`") ? " " : "";
  return `${fence}${pad}${flat}${pad}${fence}`;
}

function plural(n: number, one: string, many = `${one}s`): string {
  return `${n} ${n === 1 ? one : many}`;
}

export interface MarkdownOptions {
  /** Where the analysis ran, e.g. "orders-dev" or "the sample schema". */
  target?: string | undefined;
}

/** A PR-comment-ready summary of the review: overall rating, counts, findings, schema changes, gaps. */
export function reviewMarkdown(model: ReviewModel, options: MarkdownOptions = {}): string {
  const lines: string[] = [];
  const meta = ratingMeta(model.rating);
  lines.push(`## dbscope migration review: ${meta.label}`, "");

  const files = model.files.length;
  const against = options.target ? ` against ${escapeMarkdown(options.target)}` : "";
  const base = baseWords(model.report.base);
  lines.push(
    `${plural(files, "file")}, ${plural(model.statements.length, "statement")}, analyzed${against} with ${model.pgLabel} rules${base ? ` (base: ${base})` : ""}.`,
    "",
  );
  lines.push(RATINGS.map((r) => `**${ratingMeta(r).label}** ${model.counts[r]}`).join(" · "), "");

  const rows = sortRiskRows(riskRows(model), DEFAULT_RISK_SORT);
  if (rows.length === 0) {
    lines.push("No findings.", "");
  } else {
    lines.push("### Findings", "");
    lines.push("| Rating | Rule | Location | Relation | Finding | Safe alternative |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const r of rows) {
      lines.push(
        `| ${ratingMeta(r.rating).label} | ${codeSpan(r.ruleId)} | ${codeSpan(`${r.file}:${r.line}`)} | ${r.relation ? codeSpan(r.relation) : ""} | ${escapeMarkdown(r.message)} | ${r.safeAlternative ? escapeMarkdown(r.safeAlternative) : ""} |`,
      );
    }
    lines.push("");
  }

  const { diff } = model;
  const changes: string[] = [];
  const list = (keys: readonly string[]) => keys.map((k) => codeSpan(k)).join(", ");
  if (diff.added.length > 0) changes.push(`- Added: ${list(diff.added)}`);
  if (diff.altered.length > 0) changes.push(`- Altered: ${list(diff.altered)}`);
  if (diff.dropped.length > 0) changes.push(`- Dropped: ${list(diff.dropped)}`);
  for (const c of diff.columns) {
    const to = c.change === "renamed" && c.to ? ` to ${codeSpan(c.to)}` : "";
    changes.push(`- Column ${codeSpan(`${c.relation}.${c.column}`)} ${c.change}${to}`);
  }
  if (changes.length > 0) lines.push("### Schema changes", "", ...changes, "");

  if (model.unanalyzable.length > 0) {
    lines.push("### Not analyzed", "");
    for (const u of model.unanalyzable)
      lines.push(`- ${codeSpan(`${u.file}:${u.line}`)}: ${escapeMarkdown(u.explanation)}`);
    lines.push("");
  }
  if (model.warnings.length > 0) {
    lines.push("### Notes", "");
    for (const w of model.warnings) lines.push(`- ${escapeMarkdown(w)}`);
    lines.push("");
  }
  lines.push("_Generated by dbscope; deterministic analysis, no LLM._");
  return `${lines.join("\n")}\n`;
}
