import { describe, expect, it } from "vitest";
import { codeSpan, escapeMarkdown, reviewMarkdown } from "@/entities/migration-finding/model/markdown";
import { toReviewModel } from "@/entities/migration-finding/model/review-model";
import { migrationReport, migrationSources } from "@/test/fixtures";

describe("reviewMarkdown", () => {
  const md = reviewMarkdown(toReviewModel(migrationReport(), migrationSources()), { target: "the sample schema" });

  it("opens with the overall rating, counts and context", () => {
    const lines = md.split("\n");
    expect(lines[0]).toBe("## dbscope migration review: Critical");
    expect(lines[2]).toBe(
      "2 files, 8 statements, analyzed against the sample schema with PostgreSQL 17 rules (base: the sample schema).",
    );
    expect(lines[4]).toBe("**Critical** 2 · **High** 2 · **Medium** 3 · **Low** 1");
  });

  it("lists findings critical first as a table with locations and safe alternatives", () => {
    const rows = md
      .split("\n")
      .filter((l) => l.startsWith("| ") && !l.startsWith("| Rating") && !l.startsWith("| ---"));
    expect(rows).toHaveLength(10);
    expect(rows[0]).toMatch(/^\| Critical \| `DBS-DROP-TABLE` \| `0043_cleanup.sql:2` \| `shop.shipments` \|/);
    expect(rows[1]).toContain("`DBS-WILL-FAIL`");
    expect(rows[1]).toContain("fails without CASCADE");
    expect(rows[2]).toContain("`DBS-PARSE`");
    expect(rows.at(-1)).toMatch(/^\| Medium \|/);
    expect(md).toContain("CREATE INDEX CONCURRENTLY outside a transaction block");
  });

  it("summarizes schema changes and what was not analyzed", () => {
    expect(md).toContain("### Schema changes");
    expect(md).toContain("- Added: `shop.parcel_events`");
    expect(md).toContain("- Column `shop.customers.email` renamed to `email_address`");
    expect(md).toContain("### Not analyzed");
    expect(md).toContain("- `0043_cleanup.sql:3`: The PostgreSQL 17 grammar cannot parse this statement");
    expect(md.endsWith("_Generated by dbscope; deterministic analysis, no LLM._\n")).toBe(true);
  });

  it("escapes report text so it cannot inject Markdown or break the table", () => {
    expect(escapeMarkdown("a | b [x](http://evil) <img> *bold*\nnext")).toBe(
      "a \\| b \\[x\\](http://evil) \\<img\\> \\*bold\\* next",
    );
    expect(codeSpan("a`b|c")).toBe("``a`b\\|c``");
    const report = migrationReport();
    const first = report.statements[0];
    if (first?.findings[0]) first.findings[0].message = "evil | <script> [link](x)";
    const out = reviewMarkdown(toReviewModel(report, migrationSources()));
    expect(out).toContain("evil \\| \\<script\\> \\[link\\](x)");
    expect(out).not.toContain("<script>");
  });

  it("says when there are no findings", () => {
    const report = migrationReport();
    report.statements = report.statements.map((s) => ({ ...s, rating: "low", findings: [] }));
    report.rating = "low";
    expect(reviewMarkdown(toReviewModel(report, migrationSources()))).toContain("No findings.");
  });
});
